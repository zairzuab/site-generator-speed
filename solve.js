const KEYSET = new Set(['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary']);

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

function stringOf(raw) {
  if (raw[0] === '"') {
    if (raw.length < 2 || raw[raw.length - 1] !== '"') return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw[0] === '[') return { error: 'a bare string opens on [' };
  return { value: raw };
}

function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      let ok = raw.length === 10 && raw[4] === '-' && raw[7] === '-';
      if (ok) {
        for (let i = 0; i < 10; i++) {
          if (i === 4 || i === 7) continue;
          const c = raw[i];
          if (c < '0' || c > '9') {
            ok = false;
            break;
          }
        }
      }
      const y = ok ? Number(raw.slice(0, 4)) : 0;
      const mo = ok ? Number(raw.slice(5, 7)) : 0;
      const d = ok ? Number(raw.slice(8, 10)) : 0;
      if (!ok || y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) {
        return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      }
      return { value: raw };
    }
    case 'tags': {
      if (raw[0] !== '[' || raw[raw.length - 1] !== ']') return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      for (const t of tags) {
        if (t === '') return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
        for (let i = 0; i < t.length; i++) {
          const c = t[i];
          if (c === '"' || c === '[' || c === ']') return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
        }
      }
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout': {
      let ok = raw.length > 0;
      if (ok) {
        for (let i = 0; i < raw.length; i++) {
          const c = raw[i];
          if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '-')) {
            ok = false;
            break;
          }
        }
      }
      return ok ? { value: raw } : { error: 'key "layout": not a template name' };
    }
    case 'slug': {
      let ok = raw.length > 0 && raw.length <= 64;
      if (ok) {
        let prevDash = false;
        for (let i = 0; i < raw.length; i++) {
          const c = raw[i];
          if (c === '-') {
            if (i === 0 || i === raw.length - 1 || prevDash) {
              ok = false;
              break;
            }
            prevDash = true;
          } else if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9')) prevDash = false;
          else {
            ok = false;
            break;
          }
        }
      }
      return ok ? { value: raw } : { error: 'key "slug": not a slug' };
    }
    default:
      return { error: `unknown key "${key}"` };
  }
}

/** A source's front matter and body: { data, body }, or { error }. */
function parseFrontMatter(text) {
  if (text !== '---' && !text.startsWith('---\n')) return { error: 'no front matter' };
  let closeStart = -1;
  let bodyStart = -1;
  const idx = text.indexOf('\n---\n', 3);
  if (idx !== -1) {
    closeStart = idx + 1;
    bodyStart = idx + 5;
  } else if (text.endsWith('\n---')) {
    closeStart = text.length - 3;
    bodyStart = text.length;
  } else {
    return { error: 'the front matter is not closed' };
  }
  const region = text.slice(4, closeStart);
  const lines = region === '' ? [] : region.split('\n');
  const data = {};
  for (let li = 0; li < lines.length; li++) {
    const line = lines[li];
    const lineNo = li + 2;
    let blank = true;
    for (let j = 0; j < line.length; j++) {
      if (line[j] !== ' ' && line[j] !== '\t') {
        blank = false;
        break;
      }
    }
    if (blank || line[0] === '#') continue;
    let k = 0;
    while (k < line.length && ((line[k] >= 'a' && line[k] <= 'z') || line[k] === '_')) k++;
    if (k === 0 || line[k] !== ':') return { error: `line ${lineNo} is not "key: value"` };
    const key = line.slice(0, k);
    let raw;
    if (k + 1 === line.length) raw = '';
    else if (line[k + 1] === ' ') {
      let e = line.length;
      while (e > k + 2 && (line[e - 1] === ' ' || line[e - 1] === '\t')) e--;
      raw = line.slice(k + 2, e);
    } else {
      return { error: `line ${lineNo} is not "key: value"` };
    }
    if (!KEYSET.has(key)) return { error: `unknown key "${key}"` };
    if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  return { data, body: bodyStart === text.length ? '' : text.slice(bodyStart) };
}

// ------------------------------------------------------------------ markdown

function isBlank(line) {
  for (let j = 0; j < line.length; j++) if (line[j] !== ' ' && line[j] !== '\t') return false;
  return true;
}

function trimLine(s) {
  let a = 0;
  let b = s.length;
  while (a < b && (s[a] === ' ' || s[a] === '\t')) a++;
  while (b > a && (s[b - 1] === ' ' || s[b - 1] === '\t')) b--;
  return s.slice(a, b);
}

/** Fence-open line: its language, or null. */
function fenceOpen(line) {
  if (line[0] !== '`' || line[1] !== '`' || line[2] !== '`') return null;
  let j = 3;
  while (j < line.length) {
    const c = line[j];
    if ((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '_' || c === '+' || c === '-') j++;
    else break;
  }
  const lang = line.slice(3, j);
  while (j < line.length && (line[j] === ' ' || line[j] === '\t')) j++;
  return j === line.length ? lang : null;
}

function isFenceClose(line) {
  if (line[0] !== '`' || line[1] !== '`' || line[2] !== '`') return false;
  for (let j = 3; j < line.length; j++) if (line[j] !== ' ' && line[j] !== '\t') return false;
  return true;
}

function headingOf(line) {
  let j = 0;
  while (line[j] === '#') j++;
  if (j === 0 || j > 6) return null;
  if (line[j] !== ' ' && line[j] !== '\t') return null;
  let k = j + 1;
  while (k < line.length && (line[k] === ' ' || line[k] === '\t')) k++;
  let e = line.length;
  while (e > k && (line[e - 1] === ' ' || line[e - 1] === '\t')) e--;
  if (e === k) return null;
  return { depth: j, text: line.slice(k, e) };
}

function isHR(line) {
  const c = line[0];
  if (c !== '-' && c !== '*') return false;
  if (line[1] !== c || line[2] !== c) return false;
  for (let j = 3; j < line.length; j++) if (line[j] !== ' ' && line[j] !== '\t') return false;
  return true;
}

function bulletOf(line) {
  if ((line[0] === '-' || line[0] === '*') && line[1] === ' ') return line.slice(2);
  return null;
}

function orderedOf(line) {
  let j = 0;
  while (j < line.length && line[j] >= '0' && line[j] <= '9') j++;
  if (j === 0 || j > 9) return null;
  if (line[j] !== '.' || line[j + 1] !== ' ') return null;
  return { start: Number(line.slice(0, j)), text: line.slice(j + 2) };
}

function isContinued(line) {
  let j = 0;
  while (line[j] === ' ') j++;
  return j >= 2 && j < line.length && /\S/.test(line[j]);
}

function endsParagraph(line) {
  return isBlank(line) || fenceOpen(line) !== null || headingOf(line) !== null || isHR(line);
}

const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

/** First index from `from` where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from) {
  for (let j = from; j <= s.length - what.length; j++) {
    if (s[j] === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** First single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

/** The next inline-significant character; one shared regex, its lastIndex saved/restored around recursion. */
const SPECIAL_RE = /[\\`*\[&<>"']/g;

/** `s` rendered inline, appended to `out`; `C` carries the link resolver. */
function inlineInto(s, dir, C, out) {
  const re = SPECIAL_RE;
  const saved = re.lastIndex;
  re.lastIndex = 0;
  let start = 0;
  let m;
  while ((m = re.exec(s)) !== null) {
    let i = m.index;
    const c = m[0];
    if (c === '\\') {
      if (i + 1 < s.length && ESCAPABLE.has(s[i + 1])) {
        if (i > start) out.push(s.slice(start, i));
        const e = s[i + 1];
        out.push(e === '>' ? '&gt;' : e);
        i += 2;
        start = i;
        re.lastIndex = i;
      }
      // A backslash before anything else is itself: it stays in the plain run.
      continue;
    }
    if (c === '`') {
      const j = s.indexOf('`', i + 1);
      if (j > i + 1) {
        if (i > start) out.push(s.slice(start, i));
        out.push('<code>', escStr(s.slice(i + 1, j)), '</code>');
        i = j + 1;
        start = i;
        re.lastIndex = i;
      }
      continue;
    }
    if (c === '*') {
      if (s[i + 1] === '*') {
        const j = findUnescaped(s, '**', i + 2);
        if (j > i + 2) {
          if (i > start) out.push(s.slice(start, i));
          out.push('<strong>');
          inlineInto(s.slice(i + 2, j), dir, C, out);
          out.push('</strong>');
          i = j + 2;
          start = i;
          re.lastIndex = i;
        } else {
          // No closer: both stars are themselves, as in the reference.
          re.lastIndex = i + 2;
        }
        continue;
      }
      const j = findSingleStar(s, i + 1);
      if (j > i + 1) {
        if (i > start) out.push(s.slice(start, i));
        out.push('<em>');
        inlineInto(s.slice(i + 1, j), dir, C, out);
        out.push('</em>');
        i = j + 1;
        start = i;
        re.lastIndex = i;
      }
      continue;
    }
    if (c === '[') {
      const k = findUnescaped(s, ']', i + 1);
      const m2 = k !== -1 && s[k + 1] === '(' ? s.indexOf(')', k + 2) : -1;
      const target = m2 === -1 ? '' : s.slice(k + 2, m2);
      if (target !== '' && !/\s/.test(target)) {
        if (i > start) out.push(s.slice(start, i));
        out.push('<a href="', escStr(resolveLink(target, dir, C)), '">');
        inlineInto(s.slice(i + 1, k), dir, C, out);
        out.push('</a>');
        i = m2 + 1;
        start = i;
        re.lastIndex = i;
      }
      continue;
    }
    if (i > start) out.push(s.slice(start, i));
    out.push(ESC[c]);
    start = i + 1;
  }
  if (s.length > start) out.push(s.slice(start));
  re.lastIndex = saved;
}

function inlineStr(s, dir, C) {
  const out = [];
  inlineInto(s, dir, C, out);
  return out.join('');
}

/** `rel` from the directory `dir` of a source, or null when it climbs out of the root. */
function resolvePath(dir, rel) {
  const parts = dir === '' ? [] : dir.split('/');
  const segs = rel.split('/');
  for (let k = 0; k < segs.length; k++) {
    const seg = segs[k];
    if (seg === '' || seg === '.') continue;
    if (seg === '..') {
      if (parts.length === 0) return null;
      parts.pop();
    } else parts.push(seg);
  }
  return parts.join('/');
}

const SCHEME_RE = /^[A-Za-z][A-Za-z0-9+.-]*:/;

/** A link target's href, reporting it as broken where it names nothing. */
function resolveLink(target, dir, C) {
  if (SCHEME_RE.test(target) || target[0] === '/' || target[0] === '#') return target;
  const hash = target.indexOf('#');
  const rel = hash === -1 ? target : target.slice(0, hash);
  const frag = hash === -1 ? '' : target.slice(hash);
  const path = rel === '' ? null : resolvePath(dir, rel);
  if (path !== null) {
    const pg = C.bySource.get(path);
    if (pg !== undefined) return pg.url + frag;
    if (C.staticPaths.has(path)) return C.base + '/' + path + frag;
  }
  C.broken.add(`broken-link ${C.cur} -> ${target}`);
  return target;
}

/** `src` rendered: its HTML, its table of contents and its excerpt. */
function renderMarkdown(src, dir, C) {
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  const lines = src.split('\n');
  const n = lines.length;
  let i = 0;
  while (i < n) {
    const line = lines[i];
    if (isBlank(line)) {
      i++;
      continue;
    }
    const fence = fenceOpen(line);
    if (fence !== null) {
      const body = [];
      i++;
      while (i < n && !isFenceClose(lines[i])) body.push(lines[i++]);
      i++;
      let code = '';
      for (let k = 0; k < body.length; k++) code += escStr(body[k]) + '\n';
      blocks.push(`<pre><code${fence === '' ? '' : ` class="language-${escStr(fence)}"`}>${code}</code></pre>\n`);
      continue;
    }
    const hd = headingOf(line);
    if (hd !== null) {
      const id = uniqueSlug(slugify(hd.text), ids);
      const html = inlineStr(hd.text, dir, C);
      blocks.push(`<h${hd.depth} id="${id}">${html}</h${hd.depth}>\n`);
      if (hd.depth === 2 || hd.depth === 3) toc.push({ level: hd.depth, id, html });
      i++;
      continue;
    }
    if (isHR(line)) {
      blocks.push('<hr>\n');
      i++;
      continue;
    }
    if (line[0] === '>') {
      const body = [];
      while (i < n && lines[i][0] === '>') {
        const l = lines[i++];
        body.push(l[1] === ' ' ? l.slice(2) : l.slice(1));
      }
      const inner = [];
      for (let k = 0; k < body.length; k++) {
        const t = trimLine(body[k]);
        if (t !== '') inner.push(t);
      }
      if (inner.length === 0) blocks.push('<blockquote>\n</blockquote>\n');
      else {
        blocks.push('<blockquote>\n<p>');
        inlineInto(inner.join('\n'), dir, C, blocks);
        blocks.push('</p>\n</blockquote>\n');
      }
      continue;
    }
    const bullet = bulletOf(line);
    const ordered = bullet === null ? orderedOf(line) : null;
    if (bullet !== null || ordered !== null) {
      const isOrdered = ordered !== null;
      const items = [];
      while (i < n) {
        const m = isOrdered ? orderedOf(lines[i]) : bulletOf(lines[i]);
        if (m !== null) {
          items.push([trimLine(isOrdered ? m.text : m)]);
          i++;
        } else if (isContinued(lines[i])) {
          items[items.length - 1].push(trimLine(lines[i]));
          i++;
        } else break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const open = isOrdered && ordered.start !== 1 ? `<ol start="${ordered.start}">` : `<${tag}>`;
      blocks.push(`${open}\n`);
      for (let k = 0; k < items.length; k++) {
        blocks.push('<li>');
        inlineInto(items[k].join('\n'), dir, C, blocks);
        blocks.push('</li>\n');
      }
      blocks.push(`</${tag}>\n`);
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < n && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const text = body.join('\n');
    if (excerpt === null) {
      const tmp = [];
      inlineInto(text, dir, C, tmp);
      excerpt = tmp.join('');
      blocks.push('<p>');
      for (let k = 0; k < tmp.length; k++) blocks.push(tmp[k]);
      blocks.push('</p>\n');
    } else {
      blocks.push('<p>');
      inlineInto(text, dir, C, blocks);
      blocks.push('</p>\n');
    }
  }
  return { html: blocks.join(''), toc, excerpt: excerpt === null ? '' : excerpt };
}

