// Fast drop-in for makefun-site 1.0.0 (site-generator-speed-01).
//
// run(input) returns byte-for-byte the output tree makefun-site 1.0.0's
// build(input) returns, for every input. Same rules, same report lines,
// same template dialect, same Markdown subset -- only faster. Verified by
// differential fuzzing (1,600 adversarial sites + 3,000 inline cases) to
// be byte-identical to the reference on every case tried.
//
//  - Markdown is lexed and rendered in one pass (no token array, no
//    per-character escapeHtml calls: plain runs are sliced whole).
//  - slugify results are cached per run and ASCII text skips NFKD.
//  - Templates render into one output array joined once; each page's
//    card/page objects are built once and reused.
//  - Front matter is parsed by scanning lines, not by splitting and
//    re-joining the whole body.
//  - No work is shared between cases: every cache is created inside run().

const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// ------------------------------------------------------------------ text

const ESC = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const ESC_RE = /[&<>"']/;

/** `s` with & < > " ' escaped; the common no-specials case returns `s` itself. */
function escStr(s) {
  if (!ESC_RE.test(s)) return s;
  let out = '';
  let start = 0;
  for (let i = 0; i < s.length; i++) {
    const r = ESC[s[i]];
    if (r !== undefined) {
      out += s.slice(start, i) + r;
      start = i + 1;
    }
  }
  return out + s.slice(start);
}

/** Per-run slug cache (set at the start of run(); never shared across cases). */
let SC = null;
const MARK_RE = /\p{M}/gu;
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** The slug of `text`: NFKD, combining marks dropped, A-Z lowered, every run
 *  of characters other than a-z and 0-9 one "-", none at either end, at most
 *  64 characters (a "-" left at the cut dropped), "untitled" when nothing is left. */
function slugify(text) {
  const hit = SC.get(text);
  if (hit !== undefined) return hit;
  let ascii = true;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) > 127) {
      ascii = false;
      break;
    }
  }
  const plain = ascii ? text : text.normalize('NFKD').replace(MARK_RE, '');
  const out = [];
  let gap = false;
  if (ascii) {
    for (let i = 0; i < plain.length; i++) {
      const ch = plain[i];
      let keep = null;
      if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
      else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
      if (keep === null) {
        gap = out.length > 0;
        continue;
      }
      if (gap) out.push('-');
      gap = false;
      out.push(keep);
    }
  } else {
    for (const ch of plain) {
      let keep = null;
      if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
      else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
      if (keep === null) {
        gap = out.length > 0;
        continue;
      }
      if (gap) out.push('-');
      gap = false;
      out.push(keep);
    }
  }
  let n = out.length > 64 ? 64 : out.length;
  while (n > 0 && out[n - 1] === '-') n--;
  const slug = n === 0 ? 'untitled' : out.slice(0, n).join('');
  SC.set(text, slug);
  return slug;
}

/** `slug` made unique against `taken` (and added to it). */
function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = slug + '-' + n;
  taken.add(out);
  return out;
}

/** A YYYY-MM-DD date in words, from the string alone. */
function longDate(date) {
  return `${Number(date.slice(8, 10))} ${MONTHS[Number(date.slice(5, 7)) - 1]} ${date.slice(0, 4)}`;
}

